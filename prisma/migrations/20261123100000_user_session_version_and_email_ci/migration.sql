-- Lot 3 (sessions): User.sessionVersion, no default role, stored e-mail
-- normalised (CHECK) and unique regardless of case (functional index).
-- One table, one transaction.
--
-- Production applies pending migrations at container start
-- (docker-entrypoint.sh, `prisma migrate deploy`), and Prisma runs this file
-- as one multi-statement script, i.e. ONE implicit transaction: if any
-- statement below fails (including the two RAISEs of step 2), nothing of this
-- file is applied, the migration is recorded as failed, and the container does
-- not serve until a human resolves it (see the RAISE hints). That is why every
-- step that can refuse is written to refuse with a message naming row ids,
-- never to guess.
--
-- ORDER MATTERS FOR LOCKS. Step 1 takes ACCESS EXCLUSIVE on "User" first, so
-- every later statement runs under the strongest lock already held: no lock
-- upgrade (ROW EXCLUSIVE -> SHARE -> ACCESS EXCLUSIVE) that could deadlock
-- with a request of the still-running previous container. The cost is that
-- reads of "User" (the session gate reads it on every request) wait for the
-- whole transaction — milliseconds on a table of a few rows.

-- ---------------------------------------------------------------------------
-- STEP 1 — the two metadata-only changes (generated by `prisma migrate diff`).
-- ---------------------------------------------------------------------------
--
-- sessionVersion: INTEGER NOT NULL DEFAULT 0. Revocation counter for the JWT
-- sessions; the token carries the value read at sign-in and the session gate
-- voids it when it differs from this column. Incremented on every password
-- and role change.
--   - Why 0 on every existing row is NOT the "backfill of a new column whose
--     NULL carries a meaning" mistake: NULL would mean nothing here. 0 means
--     "never bumped", which is exactly true of every existing row, and it is
--     the value the code assigns to a token issued before this column existed
--     (such tokens carry no version). Row = 0, old token = 0: nobody is signed
--     out by the deployment. The first password or role change moves the row
--     to 1, and every older cookie of that account dies — the point of F4/H1.
--   - A database DEFAULT, not one in code: not a user-facing value (no locale,
--     no theme), and a raw-SQL creator (the bootstrap script of
--     docs/deploy-hostinger.md) must get a valid row without knowing about it.
--   - INTEGER, not BIGINT: one bump per password/role change; 2^31 of them is
--     out of reach, and the value travels in a JWT as a JS number.
--   - Constant default on ADD COLUMN: since PostgreSQL 11 this is a catalogue
--     change, no table rewrite.
--   - NO CHECK ("sessionVersion" >= 0). The gate compares for EQUALITY, so a
--     negative value revokes nothing more and revives nothing; the CHECK would
--     remove no capability from anyone. The invariant that does matter is
--     MONOTONICITY — writing back a value already issued (a reset to 0)
--     revives every cookie revoked since — and a CHECK cannot express it (it
--     needs OLD vs NEW: a BEFORE UPDATE trigger). Left to the application,
--     which only ever increments; see the comment on User.sessionVersion.
--
-- role: DROP DEFAULT. The column default was 'ADMIN' since 20260705183543, so
-- any writer forgetting the role created an administrator. Every writer in the
-- repository passes a role (repository/users.ts::create, the four upserts of
-- prisma/seed.ts, every prisma.user.create of tests-integration/). The column
-- stays NOT NULL: a raw INSERT without a role now fails with 23502 instead of
-- granting ADMIN. Existing rows are not touched — dropping a default only
-- affects future INSERTs.
ALTER TABLE "User" ADD COLUMN     "sessionVersion" INTEGER NOT NULL DEFAULT 0,
ALTER COLUMN "role" DROP DEFAULT;

-- ---------------------------------------------------------------------------
-- The e-mail normalisation, defined ONCE for steps 2 and 3.
-- ---------------------------------------------------------------------------
--
-- It must produce what lib/normalizeEmail.ts produces — `email.trim()
-- .toLowerCase()` in JS — because that is what the application will look the
-- row up with (exact match on User_email_key). A row normalised to anything
-- else becomes an account nobody can sign in to. Probed (local database,
-- PostgreSQL 16.13, glibc 2.41, en_US.utf8, provider libc; Node 22.23.2 =
-- the production image's node:22-alpine, and Node 24 — both ICU 78.2,
-- Unicode 17), the two engines are NOT the same function:
--   - btrim(x) strips U+0020 only. JS trim() strips 16 code points: U+0009-000D,
--     U+0020, U+00A0, U+1680, U+2000-200A, U+2028, U+2029, U+202F, U+205F,
--     U+3000, U+FEFF. The class below is exactly that set (probed code point
--     by code point against the JS output; it does NOT match U+0085, U+180E
--     or U+200B, which JS does not trim either). PostgreSQL's \s is not a
--     substitute: it misses U+00A0, U+202F and U+FEFF.
--   - lower() differs from toLowerCase() on 29 code points out of the 1,488
--     JS changes: U+0130 'İ' (JS 'i' + U+0307, Postgres 'i'), and 28 letters
--     added in Unicode 16/17 that glibc 2.41 does not lowercase at all (U+A7CE,
--     U+A7D2, U+A7D4, U+16EA0-U+16EB8). Plus one contextual rule no per-
--     character table shows: JS lowers a word-final capital sigma to 'ς'
--     (U+03C2), Postgres always to 'σ' ('ΟΔΟΣ' -> 'οδος' vs 'οδοσ').
--   - On pure ASCII both are the same function (A-Z -> a-z, and the ASCII part
--     of the trim set), whatever the Unicode versions.
-- Hence the rule of step 2: this file only REWRITES an e-mail that is pure
-- ASCII; a non-ASCII e-mail that would need rewriting is REFUSED, never
-- normalised by a function that disagrees with the one the application uses.
-- A non-ASCII e-mail that needs no rewriting (already lowercase, no edge
-- whitespace: 'josé@exemple.fr') is left exactly as it is.
--
-- pg_temp: the function lives only for this session and is dropped at the end
-- of the file; it is called schema-qualified, as pg_temp functions must be.
CREATE FUNCTION pg_temp.normalize_email(value text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT
  AS $fn$
    SELECT lower(regexp_replace(
      value,
      '^[\t\n\v\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+|[\t\n\v\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+$',
      '',
      'g'
    ))
  $fn$;

-- ---------------------------------------------------------------------------
-- STEP 2 — guards. They REFUSE; they never merge, pick or repair.
-- ---------------------------------------------------------------------------
--
-- Measured before writing this (read-only): local, 5 rows, 0 needing any
-- change, 0 collision; production (2026-11-23, by the coordinator), 2 rows,
-- 0 with email <> lower(btrim(email)), 0 collision. That production
-- measurement used btrim, which does not see tabs or non-breaking spaces —
-- the pre-flight query in the lot's report closes that gap. Either way the
-- guards cost nothing when the data is clean, and turn a wrong assumption
-- into a named refusal instead of a silent merge.
--
-- Messages name row IDS only, never e-mails: they end up in the container's
-- journal.
DO $guard$
DECLARE
  unsafe_ids text;
  collisions text;
BEGIN
  -- (a) Non-ASCII e-mails that would need rewriting. octet_length <>
  -- char_length is "contains a non-ASCII character" under UTF-8, independent
  -- of locale and regex classes.
  SELECT string_agg(id::text, ', ' ORDER BY id) INTO unsafe_ids
  FROM "User"
  WHERE email <> pg_temp.normalize_email(email)
    AND octet_length(email) <> char_length(email);

  IF unsafe_ids IS NOT NULL THEN
    RAISE EXCEPTION 'User e-mail normalisation refused: non-ASCII e-mail(s) needing a case or whitespace change, User.id %', unsafe_ids
      USING HINT = 'Postgres lower() and JS toLowerCase() disagree on non-ASCII text. Fix these rows by hand to the value lib/normalizeEmail.ts produces, then `prisma migrate resolve --rolled-back 20261123100000_user_session_version_and_email_ci` and redeploy.';
  END IF;

  -- (b) Accounts that would become the same account. Never merged here:
  -- which one survives (password, role, contact link, loans, projects) is a
  -- human decision.
  SELECT string_agg(ids, ' ; ') INTO collisions
  FROM (
    SELECT '(' || string_agg(id::text, ', ' ORDER BY id) || ')' AS ids
    FROM "User"
    GROUP BY pg_temp.normalize_email(email)
    HAVING count(*) > 1
  ) AS duplicate_groups;

  IF collisions IS NOT NULL THEN
    RAISE EXCEPTION 'User e-mail normalisation refused: accounts colliding once e-mails are trimmed and lowercased, User.id groups %', collisions
      USING HINT = 'Decide by hand which account of each group survives (or rename the others), then `prisma migrate resolve --rolled-back 20261123100000_user_session_version_and_email_ci` and redeploy.';
  END IF;
END
$guard$;

-- ---------------------------------------------------------------------------
-- STEP 3 — normalise the existing rows (pure ASCII ones only, by step 2).
-- ---------------------------------------------------------------------------
--
-- Touches only rows that actually change (0 locally, 0 expected in
-- production). Side effect on a row that does change: the JWTs of that
-- account carry the OLD spelling; the session gate of this base compares the
-- token e-mail exactly, so that account is signed out once and signs back in
-- (with lot 5a, which normalises the token e-mail before the lookup, it is not).
UPDATE "User"
SET email = pg_temp.normalize_email(email)
WHERE email <> pg_temp.normalize_email(email);

DROP FUNCTION pg_temp.normalize_email(text);

-- ---------------------------------------------------------------------------
-- STEP 4 — the stored e-mail IS the normalised one. CHECK.
-- ---------------------------------------------------------------------------
--
-- What it removes: the ability of ANY writer — a psql session, a data fix,
-- the bootstrap script of docs/deploy-hostinger.md — to store an address the
-- application's normalised lookup cannot find ('Jean@x.fr', 'jean@x.fr<TAB>',
-- ' jean@x.fr'), or a second case-variant of an existing one. Without it the
-- unique index of step 5 only forbids duplicates; with it, "stored" and
-- "normalised" are the same thing, which is what an exact lookup on the
-- normalised value (User_email_key) needs to be correct.
--
-- Two clauses:
--   email = lower(email) — no character Postgres knows how to lowercase.
--   no leading/trailing character of the JS trim() set — the very class of
--   pg_temp.normalize_email above, repeated here because a CHECK cannot call
--   a session-scoped function (and must not depend on any function that a
--   later DROP could take away).
--
-- Placed AFTER step 3, on purpose: a CHECK is validated against every
-- existing row the moment it is added, so before step 3 a row that this very
-- file is about to correct would abort the migration — and since production
-- migrates at container start, abort the deployment.
--
-- Gate and net agree, probed on a throwaway Postgres 16 (glibc 2.41) with the
-- output of lot 5a's normalizeEmail (`trim().toLowerCase()`, Node 22 =
-- production image): every output passes, for each of the 1,112,063 code
-- points alone, between two letters and at both edges, the 29 divergent
-- characters and 'İ' -> 'i' + U+0307 included, and word-final sigma. So the
-- application (which normalises in repository/users.ts before every write)
-- never meets this constraint: a 23514 can only come from a writer that
-- skipped the normalisation, which is the point.
--
-- Residual, cannot be closed from SQL: a raw writer storing one of the 28
-- Unicode 16/17 capitals glibc 2.41 does not know (U+A7CE, U+A7D2, U+A7D4,
-- U+16EA0-16EB8) passes `email = lower(email)` — Postgres does not see it as
-- uppercase — while JS would lowercase it.
--
-- Validated immediately (no NOT VALID): the rows were just normalised, and
-- step 2 refused every row this file could not normalise.
ALTER TABLE "User"
  ADD CONSTRAINT "User_email_normalized_check"
    CHECK (
      "email" = lower("email")
      AND "email" !~ '^[\t\n\v\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]|[\t\n\v\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]$'
    );

-- ---------------------------------------------------------------------------
-- STEP 5 — case-insensitive uniqueness. FUNCTIONAL UNIQUE INDEX.
-- ---------------------------------------------------------------------------
--
-- No two accounts whose e-mails differ only by case, whatever writes them —
-- the application, a psql session, the bootstrap script. Built and validated
-- here, inside the transaction, after step 3. No concurrent writer can slip a
-- row in between: the ACCESS EXCLUSIVE lock of step 1 is held until commit.
-- Not CONCURRENTLY: forbidden inside a transaction, and pointless on a few
-- rows under the lock already held.
--
-- With the CHECK of step 4, lower(email) = email on every row, so this index
-- and User_email_key refuse exactly the same rows. It is kept anyway as the
-- statement of intent ("unique regardless of case") that survives a future
-- relaxation of the CHECK, at the price of one btree on a table of a few
-- rows.
--
-- Agreement with the application, probed: every string JS toLowerCase()
-- produces is left unchanged by Postgres lower() (0 exceptions over all
-- 1,112,063 code points). So on values the application stores, the index key
-- IS the stored value, and the index refuses exactly the duplicates the
-- application considers duplicates — no false collision. Alone, it would
-- leave a raw writer free to store a non-normalised address, and on the
-- divergent characters even a second case-variant (probed: a raw
-- 'ΟΔΟΣ@x.gr' — key 'οδοσ@x.gr' — sat next to the application's
-- 'οδος@x.gr'); the CHECK of step 4 refuses both (lower('ΟΔΟΣ') <> 'ΟΔΟΣ').
--
-- What it is not: a lookup path. Prisma never generates `lower(email) = $1`;
-- the application looks up the normalised value with `email = $1`, served by
-- User_email_key, which is therefore KEPT (it is also what findUnique on email
-- and ON CONFLICT (email) require).
--
-- Prisma cannot express an expression index in schema.prisma. This index
-- exists ONLY here; the comment above model User is its only trace for
-- anyone reading the schema, and `prisma migrate diff` (database -> schema)
-- is silent about it (probed: empty diff on a database carrying it) — it is
-- checked in pg_indexes. A duplicate surfaces as P2002 (adapter-pg maps
-- every 23505 to it), which repository/users.ts::create already reports as
-- "duplicate" — both unique indexes of "User" are about the e-mail, so the
-- "every P2002 of this table is the e-mail" assumption of docs/CONVENTIONS.md
-- stays true. Named with Prisma's _key suffix so it reads as a unique index
-- in pg_indexes next to User_email_key.
CREATE UNIQUE INDEX "User_email_lower_key" ON "User" (lower("email"));
